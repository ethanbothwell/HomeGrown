    /// <summary>
    /// If the input is a 5-digit Oregon ZIP, returns the city name.
    /// Otherwise returns the input unchanged.
    /// </summary>
    public static string Resolve(string? input)
    {
        if (string.IsNullOrWhiteSpace(input)) return input ?? string.Empty;
        var trimmed = input.Trim();
        if (trimmed.Length == 5 && trimmed.All(char.IsDigit) && _map.TryGetValue(trimmed, out var city))
            return city;
        return trimmed;
    }
